#!/usr/bin/env bash
# Publish Harness QA results to GitHub PR
# Usage: bash publish-qa-results.sh <qa-results.json> <pr-number>

set -euo pipefail

QA_RESULTS_FILE="${1:-}"
PR_NUMBER="${2:-}"

if [ -z "$QA_RESULTS_FILE" ] || [ -z "$PR_NUMBER" ]; then
  echo "Usage: $0 <qa-results.json> <pr-number>" >&2
  echo "" >&2
  echo "Example:" >&2
  echo "  bash $0 /tmp/qa-results.json 123" >&2
  exit 1
fi

if [ ! -f "$QA_RESULTS_FILE" ]; then
  echo "Error: QA results file not found: $QA_RESULTS_FILE" >&2
  exit 1
fi

# Get GitHub token from environment
GITHUB_TOKEN="${GITHUB_TOKEN:-}"
if [ -z "$GITHUB_TOKEN" ]; then
  echo "Error: GITHUB_TOKEN environment variable not set" >&2
  echo "Set it with: export GITHUB_TOKEN=ghp_..." >&2
  exit 1
fi

# Detect repo owner and name from git remote
REPO_URL=$(git remote get-url origin 2>/dev/null || echo "")
if [ -z "$REPO_URL" ]; then
  echo "Error: Could not detect GitHub repository" >&2
  exit 1
fi

# Extract owner/repo from URL
# Handles both HTTPS and SSH URLs
REPO_PATH=$(echo "$REPO_URL" | sed -E 's|^https://github.com/||; s|^git@github.com:||; s|\.git$||')
REPO_OWNER=$(echo "$REPO_PATH" | cut -d'/' -f1)
REPO_NAME=$(echo "$REPO_PATH" | cut -d'/' -f2)

echo "📤 Publishing QA results to GitHub PR..."
echo "   Repository: $REPO_OWNER/$REPO_NAME"
echo "   PR: #$PR_NUMBER"
echo ""

# Parse QA results
TOTAL_CHECKS=$(jq 'length' "$QA_RESULTS_FILE")
PASSED=$(jq '[.[] | select(.status == "PASS")] | length' "$QA_RESULTS_FILE")
FAILED=$(jq '[.[] | select(.status == "FAIL")] | length' "$QA_RESULTS_FILE")
WARNED=$(jq '[.[] | select(.status == "WARN")] | length' "$QA_RESULTS_FILE")

echo "📊 Results Summary:"
echo "   Total: $TOTAL_CHECKS checks"
echo "   Passed: $PASSED"
echo "   Failed: $FAILED"
echo "   Warned: $WARNED"
echo ""

# Generate comment body
COMMENT_BODY=$(cat <<EOF
## 🔍 Harness QA Check Results

**Summary**: $PASSED passed, $FAILED failed, $WARNED warned (Total: $TOTAL_CHECKS checks)

EOF
)

if [ "$FAILED" -eq 0 ]; then
  COMMENT_BODY+="✅ **All checks passed!**"$'\n\n'
else
  COMMENT_BODY+="❌ **Some checks failed**"$'\n\n'
  COMMENT_BODY+="<details>"$'\n'
  COMMENT_BODY+="<summary>Failed Checks ($FAILED)</summary>"$'\n\n'

  # Extract failed checks
  while IFS= read -r failure; do
    check=$(echo "$failure" | jq -r '.check')
    detail=$(echo "$failure" | jq -r '.detail')
    why=$(echo "$failure" | jq -r '.why // ""')
    fix=$(echo "$failure" | jq -r '.fix // ""')

    COMMENT_BODY+="**$check**"$'\n'
    COMMENT_BODY+="- $detail"$'\n'
    [ -n "$why" ] && COMMENT_BODY+="- Why: $why"$'\n'
    [ -n "$fix" ] && COMMENT_BODY+="- Fix: $fix"$'\n'
    COMMENT_BODY+=$'\n'
  done < <(jq -c '.[] | select(.status == "FAIL")' "$QA_RESULTS_FILE")

  COMMENT_BODY+="</details>"$'\n\n'
fi

if [ "$WARNED" -gt 0 ]; then
  COMMENT_BODY+="<details>"$'\n'
  COMMENT_BODY+="<summary>Warnings ($WARNED)</summary>"$'\n\n'

  while IFS= read -r warning; do
    check=$(echo "$warning" | jq -r '.check')
    detail=$(echo "$warning" | jq -r '.detail')

    COMMENT_BODY+="**$check**"$'\n'
    COMMENT_BODY+="- $detail"$'\n\n'
  done < <(jq -c '.[] | select(.status == "WARN")' "$QA_RESULTS_FILE")

  COMMENT_BODY+="</details>"$'\n\n'
fi

COMMENT_BODY+="---"$'\n'
COMMENT_BODY+="_Generated by Harness QA Pipeline_"

# Escape JSON
COMMENT_JSON=$(jq -n --arg body "$COMMENT_BODY" '{body: $body}')

# Post comment to GitHub
HTTP_STATUS=$(curl -s -w "%{http_code}" -o /tmp/github-response.json \
  -X POST \
  -H "Authorization: Bearer $GITHUB_TOKEN" \
  -H "Accept: application/vnd.github+json" \
  -H "X-GitHub-Api-Version: 2022-11-28" \
  "https://api.github.com/repos/$REPO_OWNER/$REPO_NAME/issues/$PR_NUMBER/comments" \
  -d "$COMMENT_JSON")

if [ "$HTTP_STATUS" = "201" ]; then
  COMMENT_URL=$(jq -r '.html_url' /tmp/github-response.json)
  echo "✅ Comment posted successfully!"
  echo "   URL: $COMMENT_URL"
  exit 0
else
  echo "❌ Failed to post comment (HTTP $HTTP_STATUS)" >&2
  cat /tmp/github-response.json >&2
  exit 1
fi
