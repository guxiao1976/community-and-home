#!/bin/bash
# Build harness-pipeline.js from separate prompt files + core orchestration
# Run this after editing any file in .harness/agents/prompts/ or harness-pipeline-core.js
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
REPO_ROOT="$(cd "$SCRIPT_DIR/../.." && pwd)"

PROMPTS_DIR="$REPO_ROOT/.harness/agents/prompts"
WORKFLOWS_DIR="$REPO_ROOT/.harness/workflows"
OUTPUT="$WORKFLOWS_DIR/harness-pipeline.js"

# Concatenate in order: prompts first (define functions/schemas), then core (uses them)
{
  echo "// AUTO-GENERATED by .harness/scripts/build-pipeline.sh — DO NOT EDIT DIRECTLY"
  echo "// Source files:"
  echo "//   .harness/agents/prompts/generator.js  — generatorPrompt()"
  echo "//   .harness/agents/prompts/qa.js         — QA_SCHEMA + qaPrompt()"
  echo "//   .harness/agents/prompts/review.js     — REVIEW_SCHEMA + REVIEW_LENSES + reviewLensPrompt()"
  echo "//   .harness/agents/prompts/debug.js      — DEBUG_SCHEMA + debuggingPrompt()"
  echo "//   .harness/workflows/harness-pipeline-core.js — orchestration loop"
  echo "// Build: bash .harness/scripts/build-pipeline.sh"
  echo ""
  cat "$PROMPTS_DIR/generator.js" \
      "$PROMPTS_DIR/qa.js" \
      "$PROMPTS_DIR/review.js" \
      "$PROMPTS_DIR/debug.js" \
      "$WORKFLOWS_DIR/harness-pipeline-core.js"
} > "$OUTPUT"

# Verify syntax
if node --check "$OUTPUT" 2>&1; then
  echo "✅ harness-pipeline.js built successfully ($(wc -l < "$OUTPUT") lines)"
else
  echo "❌ Syntax error in built file"
  exit 1
fi
